"""What a step did to a transient, drawn.

The plotting half of the teaching document (issue #14). It lives in the library
rather than in the notebooks for one reason: **a figure that is not generated
drifts.** Real data cannot be committed, so a notebook that needs it cannot run
in CI, and figures regenerated by hand occasionally are figures that quietly
start lying — which is worse than none, because a reader trusts a picture more
than a paragraph.

Here instead, the test suite calls these on synthetic data and asserts that
**every registered filter has a figure or says why it has none**. A filter added
without one fails the suite. The notebooks stay thin: load real data, call these,
narrate.

Five shapes, not thirty-two
----------------------------
A function per filter would be thirty-two near-copies to keep in step. What
actually varies is far smaller — most filters do one of five things to a
transient — so each filter declares a *shape* and the shapes are written once.
The ones that change no measurement declare that instead, which is a statement
worth making explicitly rather than an omission.

The third panel is the point
-----------------------------
For anything with a threshold, the figure shows the quantity that was
thresholded **with the threshold drawn on it**. That is what turns "disabled
4,182 gates" into something a reader can judge, and it is the same argument R3
makes for the step report — a count is not evidence, a distribution against its
cut is.

``matplotlib`` is an optional extra
------------------------------------
``pip install ymerflow-processing[figures]``. It is deliberately not in
``install_requires``: figures are a documentation concern, and a Kubernetes
runner that only processes data should not pull a plotting stack to do it. The
import is therefore lazy, and asking for a figure without it raises a message
naming the extra rather than an ImportError from three frames down.
"""

import logging

import numpy as np

from .mask import in_use
from .filters.noise import gate_factor, recorded, scalefactor
from .pipeline import FILTER_GROUP, load_steps

log = logging.getLogger(__name__)

#: Colour carries SIGN, marker carries FATE. Red for negative is the house
#: convention in both views — a single sounding, where two moments leave colour
#: free for sign, and a profile, where a switch colours every point by sign.
#:
#: Keeping them on separate channels matters: an earlier version used red for
#: *culled*, which collides with red for *negative* on the one filter where both
#: are the subject. Colour and shape are independent, so all four combinations
#: read — and a gate that went negative and was NOT culled, which is the case a
#: reader most needs to check, becomes visible instead of indistinguishable from
#: a good one.
POSITIVE = "C0"        # blue
NEGATIVE = "C3"        # red
CULLED = "0.75"        # light grey: gone, so it recedes
BEFORE = "0.6"         # the connecting line, behind everything


def _sign_split(values):
    """``(positive, negative)`` masks over finite values."""
    finite = np.isfinite(values)
    return finite & (values >= 0), finite & (values < 0)


def _draw_transient(ax, times, values, mask, marker, size, label_prefix=""):
    """One transient, coloured by sign and marked by fate.

    Returns what it actually drew, so a legend can name only that — a legend
    entry for negatives on a sounding with none is noise.
    """
    drawn = []
    positive, negative = _sign_split(np.where(mask, values, np.nan))
    for present, colour, sign in ((positive, POSITIVE, "positive"),
                                  (negative, NEGATIVE, "negative")):
        if not present.any():
            continue
        ax.plot(times[present], np.abs(values[present]), marker, color=colour,
                markersize=size, linestyle="none",
                markeredgewidth=1.6 if marker == "x" else 0.5,
                label=f"{label_prefix}{sign}", zorder=3)
        drawn.append(sign)
    return drawn


#: The unit the arrays are stored in. Data on disk is the SimPEG format — raw
#: instrument dB/dt per unit transmitter moment, with scalefactor and GateFactor
#: applied only at read — so the plotted arrays are in instrument units and the
#: convention is fixed rather than something a figure has to assert.
#:
#: TEM-specific: dB/dt is what a time-domain instrument measures. When a second
#: method registers (#11) this belongs on the method adapter beside the gate-time
#: axis, which is the same knowledge one level up.
Y_UNIT = "instrument units"

#: What the instrument measures. TEM-specific, like the unit above.
Y_QUANTITY = "dB/dt"


def _y_label(dataset, absolute: bool = False) -> str:
    """What the vertical axis is: the quantity, then its unit.

    Built in two parts rather than one string so the absolute-value bars wrap
    the quantity alone — ``|dB/dt| [instrument units]`` rather than
    ``|dB/dt [instrument units]|``, which reads as the magnitude of a unit.
    """
    quantity = f"|{Y_QUANTITY}|" if absolute else Y_QUANTITY
    return f"{quantity} [{Y_UNIT}]"


#: What a filter does to a transient, for drawing purposes.
CULLING = "culling"            # removes data; show what went and why
TRANSFORM = "transform"        # changes values; show before against after
UNCERTAINTY = "uncertainty"    # changes the error bars rather than the values
GEOMETRY = "geometry"          # acts per sounding, not per gate; show the line
NOTHING = "nothing"            # changes no measurement — say so, do not draw

#: Which shape each registered filter draws in. **Every filter must appear**, and
#: a test enforces that: a filter added without an entry fails the suite rather
#: than silently having no figure.
#:
#: ``NOTHING`` is a claim, not an omission. Renaming an array or exporting a file
#: changes no measurement, so there is nothing a before-and-after transient could
#: show, and drawing one would imply otherwise.
SHAPES = {
    # Data removed. The interesting half is always *what went and why*.
    "cull_below_noise_floor": CULLING,
    "cull_by_curvature": CULLING,
    "cull_by_slope": CULLING,
    "cull_near_infrastructure": CULLING,
    "cull_by_misfit": CULLING,
    "cull_by_altitude_tilt": CULLING,
    "cull_by_uncertainty": CULLING,
    "cull_negatives": CULLING,
    "cull_sparse_soundings": CULLING,
    "set_inuse_gates": CULLING,
    "apply_manual_edits": CULLING,

    # Values changed. Before against after, on the same axes.
    "average_along_line": TRANSFORM,
    "correct_tilt_1d": TRANSFORM,
    "apply_nominal_current": TRANSFORM,
    "add_noise": TRANSFORM,
    "compute_misfit": TRANSFORM,

    # The error bars are the subject, so drawing the values alone would miss it.
    "assign_uncertainty": UNCERTAINTY,
    "set_noise_floor": UNCERTAINTY,
    "inflate_uncertainty": UNCERTAINTY,

    # Per sounding rather than per gate: a transient plot says nothing useful.
    "classify_lines": GEOMETRY,
    "select_lines": GEOMETRY,
    "apply_terrain_model": GEOMETRY,
    "zero_attitude": GEOMETRY,

    # Changes no measurement.
    "copy_array": NOTHING,
    "copy_attribute": NOTHING,
    "remove_array": NOTHING,
    "remove_attribute": NOTHING,
    "rename_array": NOTHING,
    "rename_attribute": NOTHING,
    "select_moments": NOTHING,
    "export_vector": NOTHING,
}


class FiguresUnavailable(ImportError):
    """Raised when matplotlib is not installed; figures are an optional extra."""


def _figure_class():
    """matplotlib's Figure, or a message naming the extra.

    ``Figure`` directly rather than ``pyplot.figure()``: pyplot keeps every
    figure it creates in a global registry until someone closes it, so a library
    drawing thirty of them leaks thirty. Constructing the class needs no
    backend and no global state, and the caller can still ``savefig`` or hand it
    to a notebook.
    """
    try:
        from matplotlib.figure import Figure
    except ImportError as exc:
        raise FiguresUnavailable(
            "Figures need matplotlib, which is an optional extra: "
            "pip install ymerflow-processing[figures]. It is kept out of the "
            "required dependencies because a runner that only processes data "
            "should not pull a plotting stack to do it."
        ) from exc
    return Figure


def available() -> bool:
    """Whether figures can be drawn in this environment.

    Returns
    -------
    bool
        ``True`` if matplotlib imports.
    """
    try:
        _figure_class()
    except FiguresUnavailable:
        return False
    return True


def missing_shapes() -> list[str]:
    """Registered filters with no declared figure shape.

    The list a test asserts is empty. A filter added without an entry in
    :data:`SHAPES` has no figure and nothing says so, which is exactly how the
    teaching document would come to describe thirty-one of thirty-two filters
    while looking complete.

    Returns
    -------
    list[str]
        Registered filter names with no entry in :data:`SHAPES`.
    """
    return sorted(set(load_steps(FILTER_GROUP)) - set(SHAPES))


# ── Reading a transient out of a dataset ─────────────────────────────────────

def _transient(dataset, channel, sounding: int):
    """One sounding's gate times and values, with culled gates as NaN.

    Culled gates are blanked rather than dropped so the two sides of a figure
    stay on the same x axis: a gate that went should leave a hole where it was,
    which is the thing a reader is looking for.
    """
    values = dataset.layer_data[channel.data_key].to_numpy(dtype=float)[sounding]
    times = np.asarray(channel.axis.values, dtype=float)
    if times.size != values.size:
        times = np.arange(values.size, dtype=float)
    live = in_use(dataset, channel)[sounding]
    return times, np.where(live, values, np.nan), live


def _decorate(ax, channel, times):
    """Log-log axes, which is the only way a transient is readable.

    A transient falls three or four orders of magnitude across its gates. On
    linear axes every gate after the first few is indistinguishable from zero,
    so the plot shows one point and a flat line where the data is.
    """
    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xlabel(f"{channel.axis.name or 'gate'} [{channel.axis.unit or 's'}]")
    ax.grid(True, which="both", alpha=0.25, linewidth=0.5)


def _culling(fig, before, after, channel, sounding, report):
    """Before, after, and the gates that went — plus what they were judged on."""
    threshold = _thresholded(report, before, after, channel, sounding)
    axes = fig.subplots(1, 2 if threshold else 1, squeeze=False)[0]

    times, kept, live_after = _transient(after, channel, sounding)
    _, was, live_before = _transient(before, channel, sounding)

    ax = axes[0]
    # The line only — grey, behind, so the eye follows the shape of the decay
    # while the markers carry sign and fate.
    ax.plot(times, np.abs(was), "-", color=BEFORE, linewidth=1, zorder=1)

    # Culled gates in light grey rather than by sign: they are gone, so they
    # should recede and let the eye follow what survived. Sign colouring is
    # reserved for data that is still in play, which is where a reader has a
    # decision to make about it.
    went = live_before & ~live_after
    if went.any():
        ax.plot(times[went], np.abs(was[went]), "x", color=CULLED,
                markersize=8, markeredgewidth=1.8, linestyle="none",
                label=f"culled ({int(went.sum())})", zorder=2)
    _draw_transient(ax, times, was, live_after, "o", 4)
    _decorate(ax, channel, times)
    ax.set_ylabel(_y_label(after, absolute=True))
    ax.legend(fontsize=8, frameon=False)
    ax.set_title(f"{channel}", fontsize=9)

    if threshold:
        name, values, limit = threshold
        ax2 = axes[1]
        width = min(len(values), len(times))
        # Only the gates this step could act on. One already culled is not
        # evidence about this filter's threshold, and leaving it in makes the
        # panel disagree with the left one about what was under consideration.
        looked_at = live_before[:width]
        x = np.where(looked_at, times[:width], np.nan)
        y = np.where(looked_at, values[:width], np.nan)
        ax2.plot(x, y, "o-", color="C0", markersize=3.5, linewidth=1.2)

        # The gates that exceeded it, marked the same way as on the left. A
        # relative uncertainty runs from a few percent to infinity where the
        # floor has overtaken the signal, so a LINEAR axis scaled to the
        # visible data drops exactly the points that were cut — the panel
        # meant to show why gates went was excluding them from its own scale.
        over = np.isfinite(y) & (y > limit)
        if over.any():
            ax2.plot(x[over], y[over], "x", color="C3", markersize=8,
                     markeredgewidth=1.6, label=f"over ({int(over.sum())})")
        ax2.set_yscale("log")

        # The threshold drawn on the quantity it cut, which is what makes a
        # count of culled gates into something judgeable.
        ax2.axhline(limit, color="C3", linestyle="--", linewidth=1.2,
                    label=f"threshold {limit:g}")
        ax2.set_xscale("log")
        ax2.set_xlabel(f"{channel.axis.name or 'gate'} "
                       f"[{channel.axis.unit or 's'}]")
        ax2.set_ylabel(name)
        ax2.legend(fontsize=8, frameon=False)
        ax2.grid(True, which="both", alpha=0.25, linewidth=0.5)
    return fig


#: Which dataset array holds the quantity a culling step judged on, for the
#: steps where it is a stored array rather than something derived on the fly.
#: Curvature and decay rate are computed inside their filters and never stored,
#: so they get one panel rather than a fabricated second one — drawing a
#: recomputed series risks disagreeing with the report beside it.
THRESHOLDED = {"max_uncertainty": ("relative uncertainty", "std_key")}


def _thresholded(report, before, after, channel, sounding):
    """The quantity a culling step judged on, its series, and its cut.

    The cut is read from the step report rather than recomputed: R3 already
    records the parameters actually used, and a figure that re-derived one could
    disagree with the report printed beside it.

    ``None`` where the quantity is not a stored array. Half a panel is worse
    than none: a threshold line drawn against the wrong series is a figure that
    lies confidently.
    """
    if report is None:
        return None
    distributions = getattr(report, "distributions", None) or {}
    for parameter, (label, attribute) in THRESHOLDED.items():
        limit = distributions.get(parameter)
        if limit is None:
            continue
        key = getattr(channel, attribute, None)
        # Read from `after` first. The quantity is the one the filter JUDGED on,
        # and on a raw delivery it does not exist beforehand — uncertainty is
        # created mid-run by assign_uncertainty. Culling does not change it, so
        # `after` holds what the filter saw. Falling back to `before` covers a
        # delivery that shipped its own.
        for source in (after, before):
            if key and key in source.layer_data:
                series = source.layer_data[key].to_numpy(dtype=float)[sounding]
                return label, np.abs(series), float(limit)
        # Not stored under this parameter's key; the next thresholded
        # parameter may be. Returning here skipped them all.
    return None


def _transform(fig, before, after, channel, sounding, report):
    """The same transient, before and after, on one pair of axes."""
    ax = fig.subplots()
    times, now, _ = _transient(after, channel, sounding)
    _, was, _ = _transient(before, channel, sounding)

    ax.plot(times, np.abs(was), "o-", color="0.6", markersize=3.5,
            linewidth=1, label="before")
    ax.plot(times, np.abs(now), "o-", color="C0", markersize=3.5,
            linewidth=1.2, label="after")
    _decorate(ax, channel, times)
    ax.set_ylabel(_y_label(after, absolute=True))
    ax.legend(fontsize=8, frameon=False)
    ax.set_title(f"{channel}", fontsize=9)
    return fig


def _uncertainty(fig, before, after, channel, sounding, report):
    """The error bars, which are the subject — the values may not move at all."""
    ax = fig.subplots()
    times, values, _ = _transient(after, channel, sounding)
    ax.plot(times, np.abs(values), "-", color="0.85", linewidth=1, zorder=0)

    for dataset, colour, label in ((before, "0.6", "before"),
                                   (after, "C0", "after")):
        key = channel.std_key
        if not key or key not in dataset.layer_data:
            continue
        relative = dataset.layer_data[key].to_numpy(dtype=float)[sounding]
        # The stored uncertainty is *relative*, so the drawn bar is that
        # fraction of the datum. Plotting the fraction itself would put a
        # spread of order one on every gate whatever its magnitude.
        spread = np.abs(relative) * np.abs(values)
        ax.errorbar(times, np.abs(values), yerr=spread, fmt="o", color=colour,
                    markersize=3, linewidth=0, elinewidth=1, capsize=2,
                    label=label)
    # set_noise_floor records a model and writes no uncertainty array, so
    # there may be nothing to put error bars on. Draw the floor it estimated
    # instead — that IS what the step produced, and it is the thing a reader
    # wants to see against the transient.
    model = recorded(after)
    if model is not None and model.level_1ms is not None:
        # Only across the gates that are actually there. The axis carries every
        # gate the system description declares, including the early ones
        # disabled at load — drawing the floor across all of them stretches the
        # x axis a decade to the left of any data and leaves the transient
        # squashed into a corner.
        live = np.isfinite(values)
        span = times[live] if live.any() else times
        floor = model.floor_in_array_units(
            span,
            dipole_moment=getattr(channel, "dipole_moment", None),
            scalefactor=scalefactor(after),
            gate_factor=gate_factor(after, channel))
        ax.plot(span, np.abs(floor), "--", color="C3", linewidth=1.4,
                label="estimated noise floor")

    _decorate(ax, channel, times)
    ax.set_ylabel(_y_label(after, absolute=True) + ", with uncertainty")
    # legend() on an axes with nothing labelled warns rather than drawing
    # nothing, which is noise on a correct path.
    if ax.get_legend_handles_labels()[0]:
        ax.legend(fontsize=8, frameon=False)
    ax.set_title(f"{channel}", fontsize=9)
    return fig


def _geometry(fig, before, after, channel, sounding, report):
    """Where the soundings are, since these steps act per sounding not per gate."""
    ax = fig.subplots()
    xyz = after.survey.xyz
    frame = after.flightlines
    if xyz.x_column in frame.columns and xyz.y_column in frame.columns:
        ax.plot(frame[xyz.x_column], frame[xyz.y_column], ".", color="C0",
                markersize=2)
        ax.set_xlabel(xyz.x_column)
        ax.set_ylabel(xyz.y_column)
        ax.set_aspect("equal", adjustable="datalim")
    ax.grid(True, alpha=0.25, linewidth=0.5)
    return fig


_DRAW = {CULLING: _culling, TRANSFORM: _transform,
         UNCERTAINTY: _uncertainty, GEOMETRY: _geometry}


def figure(step: str, before, after, report=None, channel=None,
           sounding: int = 0, figsize=None):
    """Draw what ``step`` did, as a matplotlib ``Figure``.

    Parameters
    ----------
    step : str
        The registered filter name, which selects the shape.
    before : Dataset
        The dataset as it was. Take a ``copy()`` before running.
    after : Dataset
        The dataset the step returned.
    report : StepReport | None
        That step's report, for the threshold it cut on.
    channel : Channel | None
        Which channel to draw. The first, if unset.
    sounding : int
        Which sounding's transient to draw.
    figsize : tuple[float, float] | None
        The figure size in inches; matplotlib's default if unset.

    Returns
    -------
    Figure or None
        ``None`` for a step declared as changing no measurement — there is
        nothing a before-and-after transient could show, and drawing one
        would imply otherwise.

    Raises
    ------
    FiguresUnavailable
        When matplotlib is not installed, naming the extra that provides it.
    """
    shape = SHAPES.get(step)
    if shape is None:
        raise KeyError(
            f"No figure shape declared for {step!r}. Add it to figures.SHAPES — "
            f"including as {NOTHING!r} if it changes no measurement, which is a "
            f"claim worth making rather than an omission.")
    if shape == NOTHING:
        return None

    Figure = _figure_class()
    channel = channel or (after.channels[0] if after.channels else None)
    if channel is None:
        return None

    fig = Figure(figsize=figsize or (9 if shape == CULLING else 5.5, 3.6))
    fig.suptitle(step, fontsize=10, fontweight="bold")
    _DRAW[shape](fig, before, after, channel, sounding, report)
    fig.tight_layout()
    return fig
